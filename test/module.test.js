const assert = require("assert");
const path = require("path");
const file = path.resolve(__dirname,"../src/module.js");
const { createMappingModule }=require("./load")(file);
const components={MappingMap:()=>null,icon:null,menuText:"Mapping dashboard"};
assert.equal(createMappingModule({},components)["core.Router"],undefined);
assert.equal(createMappingModule({enabled:true},components)["core.Router"],undefined);
const result=createMappingModule({enabled:true,viewRights:["121901"],menuContributionKey:"openSearchReports.MainMenu"},components);
assert.equal(result["core.Router"][0].path,"mapping/dashboard");
assert.equal(result.refs[0].key,"mapping.MappingMap");
const entry=result["openSearchReports.MainMenu"][0];
assert.equal(entry.filter([121901]),true);
assert.equal(entry.filter([]),false);
assert.equal(entry.route,"/mapping/dashboard");
assert.throws(()=>createMappingModule({enabled:true,viewRights:[1],menuContributionKey:"core.MainMenu"},components));
assert.equal(createMappingModule({enabled:true,viewRights:[954001]},components)["openSearchReports.MainMenu"][0].filter([954001]),true);
const { hasCapability }=require("./load")(path.resolve(__dirname,"../src/configuration.js"));
assert.equal(hasCapability([954001],["954001"]),true);
assert.equal(hasCapability([954001],["954001","954002"]),false);
assert.equal(hasCapability([954001],[]),false);
console.log("Mapping module disabled-state, capability and host menu tests passed.");
