const assert = require("assert");
const Module = require("module");
const path = require("path");
const babel = require("@babel/core");
const source = path.resolve(__dirname, "../src/geo/geometry.js");
const { code } = babel.transformFileSync(source, { presets: [["@babel/preset-env", { modules: "commonjs" }]], babelrc: false });
const loaded = new Module(source, module);
loaded.filename = source;
loaded.paths = Module._nodeModulePaths(path.dirname(source));
loaded._compile(code, source);
const { polygonPaths, fitPaths } = loaded.exports;
const polygon = { type: "Polygon", coordinates: [[[33, -14], [34, -14], [34, -13], [33, -14]]] };
const projected = polygonPaths(polygon);
const fitted = fitPaths([{ id: "pilot", paths: projected }]);
assert.equal(fitted.layers.length, 1);
assert.match(fitted.layers[0].paths[0], /^M.*Z$/);
assert.ok(!fitted.layers[0].paths[0].includes("NaN"));
assert.equal(fitPaths([]).layers.length, 0);
assert.throws(() => polygonPaths({ type: "Point", coordinates: [0, 0] }));
assert.throws(() => polygonPaths({ type: "Polygon", coordinates: [[[999, 0], [999, 0], [999, 0], [999, 0]]] }));
const withHole = { ...polygon, coordinates: [...polygon.coordinates, [[33.1, -13.9], [33.2, -13.9], [33.2, -13.8], [33.1, -13.9]]] };
assert.equal(polygonPaths(withHole)[0].length, 2);
assert.equal(polygonPaths({ type: "MultiPolygon", coordinates: [polygon.coordinates, polygon.coordinates] }).length, 2);
console.log("Geospatial projection, polygon holes and fit tests passed.");
const { projectPoint } = loaded.exports;
const origin=projectPoint([0,0]);
assert.equal(origin[0],0);
assert.ok(Math.abs(origin[1])<1e-10);
assert.throws(() => projectPoint([33,null]));
assert.throws(() => projectPoint([33,91]));
assert.throws(() => projectPoint([181,0]));
assert.throws(() => projectPoint([33,NaN]));
assert.throws(() => projectPoint(['33',-14]));
assert.ok(projectPoint([0,90]).every(Number.isFinite));
const pointOnly=fitPaths([],[{id:'point',point:projectPoint([33,-14])}]);
assert.equal(pointOnly.layers.length,0);
assert.deepEqual(pointOnly.markers[0].point,[400,240]);
const combined=fitPaths([{id:'district',paths:projected}],[{id:'outside',point:projectPoint([35,-12])}]);
assert.equal(combined.markers.length,1);
assert.ok(combined.markers[0].point[0]>=30 && combined.markers[0].point[0]<=770);
assert.ok(combined.markers[0].point[1]>=30 && combined.markers[0].point[1]<=450);
console.log('Point-only and combined boundary/point projection checks passed.');
